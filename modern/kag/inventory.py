"""inventory.py: read-only inventory of the PEM knowledge graph.

Writes modern/docs/reports/graph-inventory.md: node counts per label (with the loaders that created them), relationship
counts per type (with their label patterns), and 3 example rows per label (lowest keys, long values shortened).
Uses the same NEO4J_* environment variables as the loaders; it only runs MATCH queries.

Run:  python inventory.py [--out PATH]
"""
import argparse
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "loaders"))
import common  # noqa: E402

HIDDEN = {"source", "loader", "loadedAt"}
MAX_PROPS, MAX_LEN = 6, 70


def short(v) -> str:
    s = ", ".join(map(str, v)) if isinstance(v, list) else str(v)
    s = " ".join(s.split()).replace("|", "/")
    return s if len(s) <= MAX_LEN else s[:MAX_LEN - 1] + "…"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(common.REPO / "modern/docs/reports/graph-inventory.md"))
    a = ap.parse_args()
    driver, db = common.connect()
    with driver.session(database=db) as s:
        labels = s.run("MATCH (n) UNWIND labels(n) AS l RETURN l, count(*) AS c ORDER BY l").data()
        loaders = {r["l"]: r["ls"] for r in s.run(
            "MATCH (n) UNWIND labels(n) AS l WITH l, n.loader AS ldr, count(*) AS c ORDER BY c DESC "
            "RETURN l, collect(coalesce(ldr, '?') + ' (' + toString(c) + ')') AS ls").data()}
        rels = s.run("MATCH ()-[r]->() RETURN type(r) AS t, count(*) AS c ORDER BY t").data()
        pats = s.run("MATCH (a)-[r]->(b) RETURN type(r) AS t, labels(a)[0] AS f, labels(b)[0] AS to, count(*) AS c "
                     "ORDER BY t, c DESC").data()
        examples = {}
        for row in labels:
            lab = row["l"]
            key = common.LABEL_KEYS.get(lab)
            order = f"ORDER BY n.`{key}`" if key else ""
            examples[lab] = (key, [r["p"] for r in s.run(f"MATCH (n:`{lab}`) RETURN properties(n) AS p {order} LIMIT 3").data()])
    driver.close()

    total_n = sum(r["c"] for r in labels)
    total_r = sum(r["c"] for r in rels)
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    out = [f"# Knowledge graph inventory (`{db}`)", "",
           f"Generated by `modern/kag/inventory.py` on {now} with read-only queries. "
           f"**{total_n} nodes in {len(labels)} labels, {total_r} relationships in {len(rels)} types.** "
           "Re-run it after any load to refresh this file.", "",
           "## Nodes per label", "", "| Label | Nodes | Key property | Created by (loader, nodes) |", "|---|---:|---|---|"]
    for r in labels:
        out.append(f"| {r['l']} | {r['c']} | `{common.LABEL_KEYS.get(r['l'], '-')}` | {', '.join(loaders.get(r['l'], []))} |")
    out += ["", "## Relationships per type", "", "| Type | Count | Patterns (from -> to: count) |", "|---|---:|---|"]
    for r in rels:
        p = "; ".join(f"{x['f']} -> {x['to']}: {x['c']}" for x in pats if x["t"] == r["t"])
        out.append(f"| {r['t']} | {r['c']} | {p} |")
    out += ["", "## Three example rows per label", "",
            f"The 3 nodes with the lowest key; at most {MAX_PROPS} properties each (key first; provenance properties "
            f"`source`, `loader`, `loadedAt` hidden); values longer than {MAX_LEN} characters are shortened.", ""]
    for lab, (key, rows) in examples.items():
        cols = [key] if key else []
        for p in rows:
            for k in sorted(p):
                if k not in HIDDEN and k not in cols and len(cols) < MAX_PROPS:
                    cols.append(k)
        out += [f"### {lab}", "", "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
        for p in rows:
            out.append("| " + " | ".join(short(p.get(c, "")) for c in cols) + " |")
        out.append("")
    Path(a.out).write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"{total_n} nodes / {len(labels)} labels, {total_r} relationships / {len(rels)} types -> {common.rel_path(Path(a.out))}")
    for r in labels:
        print(f"  {r['l']:<20} {r['c']:>6}")
    for r in rels:
        print(f"  :{r['t']:<19} {r['c']:>6}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
