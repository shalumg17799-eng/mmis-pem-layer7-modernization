#!/usr/bin/env bash
# Creates modern/infra/.env.local with random local-only secrets, once. It never prints the values.
# The file is git-ignored (root .gitignore). Delete it and run `make reset` to rotate every secret.
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
file="$here/.env.local"
if [ -f "$file" ]; then
  echo "kept existing $file"
  exit 0
fi
rnd() { head -c 24 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 24; }
umask 077
{
  echo "# Generated by infra/scripts/gen-env-local.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Local only; never commit."
  echo "PG_ADMIN_PASSWORD=$(rnd)"
  for svc in PROVIDER ENROLLMENT SCREENING RISK REVALIDATION SANCTIONS NOTIFICATION DIRECTORY TMSIS; do
    echo "PG_${svc}_PASSWORD=$(rnd)"
  done
  echo "KC_BOOTSTRAP_ADMIN_PASSWORD=$(rnd)"
  echo "KC_PROVIDER_PASSWORD=$(rnd)"
  echo "KC_ANALYST_PASSWORD=$(rnd)"
  echo "KC_SUPERVISOR_PASSWORD=$(rnd)"
  echo "KC_ADMIN_PASSWORD=$(rnd)"
  echo "PEM_SERVICES_CLIENT_SECRET=$(rnd)"
} > "$file"
echo "created $file (values not shown)"
